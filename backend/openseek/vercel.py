from .config import ConfigError, Settings

log = logging.getLogger("openseek.vercel")
runtime_core: Core | None = None


class VercelGuard:
    """Dispatch owner routes through owner auth and all API routes through device auth."""

    def __init__(self, app, core: Core):
        self.api = Guard(app, core)
        self.admin = Guard(app, core, admin=True)

    async def __call__(self, scope, receive, send):
        path = scope.get("path", "")
        if scope.get("type") == "http" and (path == "/" or path.startswith("/admin/")):
            return await self.admin(scope, receive, send)
        return await self.api(scope, receive, send)


